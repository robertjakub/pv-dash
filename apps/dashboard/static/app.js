function aggregateBuckets(p, view) {
  const stepS = p.t.length > 1 ? (p.t[1] - p.t[0]) / 1000 : 0;
  let labels, keyOf, keys;
  if (view === 'month') {
    const s0 = new Date(state.axis[0]);
    const dim = new Date(s0.getFullYear(), s0.getMonth() + 1, 0).getDate();
    labels = Array.from({ length: dim }, (_, i) => String(i + 1).padStart(2, '0'));
    keyOf = d => d.getDate();
  } else if (view === 'all') {
    const y0 = new Date(state.axis[0]).getFullYear();
    const y1 = new Date().getFullYear();
    labels = [];
    for (let y = y0; y <= y1; y++) labels.push(String(y));
    keyOf = d => d.getFullYear();
  } else {
    labels = t('monthsShort');
    keyOf = d => d.getMonth();
  }
  const acc = new Map();
  const nCols = 3;
  for (let i = 1; i < p.t.length; i++) {
    const d = new Date(p.t[i]);
    const k = keyOf(d);
    if (!acc.has(k)) acc.set(k, Array(nCols).fill(0));
    const a = acc.get(k);
    const chg = state.battActive && p.chg ? p.chg[i] : 0;
    const dis = state.battActive && p.dis ? p.dis[i] : 0;
    a[0] += (p.pv[i] + dis) * stepS / 3600;
    a[1] += (p.load[i] + chg) * stepS / 3600;
    a[2] += (p.fromPv[i] + chg) * stepS / 3600;
  }
  if (keys === undefined) keys = labels.map((_, li) => view === 'month' ? li + 1 : view === 'all' ? Number(labels[li]) : li);
  const pick = idx => keys.map(k => {
    const a = acc.get(k);
    return a ? a[idx] : null;
  });
  return { labels, pv: pick(0), load: pick(1), fromPv: pick(2) };
}
