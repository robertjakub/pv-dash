function localUtcOffset() {
  const o = -new Date().getTimezoneOffset();
  const a = Math.abs(o);
  return (o < 0 ? '-' : '+') + String(Math.floor(a / 60)).padStart(2, '0') + ':' + String(a % 60).padStart(2, '0');
}

function expectedBuckets(mode) {
  const [s, e] = state.axis;
  const pad = n => String(n).padStart(2, '0');
  const off = localUtcOffset();
  const out = [];
  if (mode === 'hour') {
    for (let t = s; t < e; t += 3600000) {
      const d = new Date(t);
      out.push({ key: Math.floor(t / 3600000), label: d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate()) + 'T' + pad(d.getHours()) + ':00:00' + off });
    }
  } else if (mode === 'day') {
    const d0 = new Date(s);
    const last = new Date(d0.getFullYear(), d0.getMonth() + 1, 0).getDate();
    for (let day = 1; day <= last; day++) {
      out.push({ key: d0.getFullYear() * 10000 + (d0.getMonth() + 1) * 100 + day, label: d0.getFullYear() + '-' + pad(d0.getMonth() + 1) + '-' + pad(day) });
    }
  } else {
    const y = new Date(s).getFullYear();
    for (let m = 1; m <= 12; m++) out.push({ key: y * 100 + m, label: y + '-' + pad(m) });
  }
  return out;
}

function groupPowerStats(t, vals, mode, fill = true) {
  const pad = n => String(n).padStart(2, '0');
  const off = localUtcOffset();
  const groups = new Map();
  if (fill && mode !== 'year') for (const b of expectedBuckets(mode)) groups.set(b.key, { label: b.label, max: 0, sum: 0, n: 0 });
  for (let i = 0; i < t.length; i++) {
    const d = new Date(t[i]);
    let key;
    if (mode === 'year') key = d.getFullYear();
    else if (mode === 'month') key = d.getFullYear() * 100 + (d.getMonth() + 1);
    else if (mode === 'day') key = d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate();
    else key = Math.floor(t[i] / 3600000);
    let g = groups.get(key);
    if (!g) { g = { label: mode === 'year' ? String(d.getFullYear()) : mode === 'month' ? d.getFullYear() + '-' + pad(d.getMonth() + 1) : mode === 'day' ? d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate()) : d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate()) + 'T' + pad(d.getHours()) + ':00:00' + off, max: 0, sum: 0, n: 0 }; groups.set(key, g); }
    if (vals[i] > g.max) g.max = vals[i];
    g.sum += vals[i];
    g.n++;
  }
  return [...groups.keys()].sort((a, b) => a - b).map(k => [groups.get(k).label, groups.get(k).max, groups.get(k).n ? groups.get(k).sum / groups.get(k).n : 0, groups.get(k).sum]);
}

function energyWhPerGroup(groupMode, fill = true) {
  const p = state.series;
  if (!p || !p.t.length) return null;
  const stepS = state.lastStepSec || (p.t.length > 1 ? (p.t[1] - p.t[0]) / 1000 : 0);
  const wh = arr => groupPowerStats(p.t, arr, groupMode, fill).map(r => r[3] * stepS / 3.6);
  const out = { pv: wh(p.pv), load: wh(p.load), exp: wh(p.exp), imp: wh(p.imp) };
  if (state.battActive) { out.chg = wh(p.chg); out.dis = wh(p.dis); }
  return out;
}

