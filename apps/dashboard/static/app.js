function tick(now) {
  const dt = Math.min(0.05, (now - lastFrame) / 1000);
  lastFrame = now;
  for (const f of flowDefs) {
    if (f.kw > 0.004) {
      const rate = Math.min(14, 1.5 + 2.4 * Math.sqrt(f.kw));
      f.acc += rate * dt;
      while (f.acc >= 1) {
        f.acc -= 1;
        f.parts.push({ p: 0, node: spawnDot(f) });
      }
    }
    const speed = (80 + 150 * Math.min(2.4, Math.sqrt(f.kw))) / f.len;
    for (const q of f.parts) q.p += speed * dt;
    f.parts = f.parts.filter(q => {
      if (q.p >= 1) { q.node.remove(); return false; }
      return true;
    });
    for (const q of f.parts) {
      const pt = f.el.getPointAtLength(q.p * f.len);
      q.node.setAttribute('transform', `translate(${pt.x.toFixed(1)},${pt.y.toFixed(1)})`);
      q.node.setAttribute('opacity', Math.min(1, q.p / 0.1, (1 - q.p) / 0.1).toFixed(2));
    }
  }
  requestAnimationFrame(tick);
}
