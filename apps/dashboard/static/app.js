function detectLang() {
  const avail = Object.keys(I18N);
  const cands = [qs.get('lang'), ls.get('pv_lang'), CFG.defaultLang, ...(navigator.languages || []), navigator.language];
  for (const c of cands) {
    if (!c) continue;
    const l = String(c).toLowerCase();
    if (avail.includes(l)) return l;
    const base = l.split('-')[0];
    if (avail.includes(base)) return base;
  }
  return 'en';
}
