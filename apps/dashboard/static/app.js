function energyIn(v, startUnit) {
  let u = startUnit, x = v;
  const down = { MWh: ['kWh', 1000], kWh: ['Wh', 1000] };
  const up = { Wh: ['kWh', 1000], kWh: ['MWh', 1000] };
  while (Math.abs(x) < 1 && down[u]) { x *= down[u][1]; u = down[u][0]; }
  while (Math.abs(x) >= 1000 && up[u]) { x /= up[u][1]; u = up[u][0]; }
  return [x, u];
}
function fmtEnergy(v, startUnit, trim) {
  if (!isFinite(v)) v = 0;
  const [x, u] = energyIn(v, startUnit);
  let s = u === 'Wh' ? String(Math.round(x)) : x.toFixed(2);
  if (trim) s = s.replace(/\.0+$/, '').replace(/(\.\d*?)0+$/, '$1');
  return s + ' ' + u;
}
