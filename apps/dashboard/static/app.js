function smoothSeries(t, vals, windowMs) {
  if (!windowMs || vals.length < 3) return vals;
  const half = windowMs / 2;
  return vals.map((_, i) => {
    let sum = 0, n = 0;
    for (let j = i; j >= 0 && t[i] - t[j] <= half; j--) { sum += vals[j]; n++; }
    for (let j = i + 1; j < vals.length && t[j] - t[i] <= half; j++) { sum += vals[j]; n++; }
    return sum / n;
  });
}
function hexToRgba(hex, a) {
  const n = parseInt(hex.slice(1), 16);
  return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`;
}
