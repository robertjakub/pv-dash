    g.lineTo(X(p.t[p.t.length - 1]), H - padB);
    g.lineTo(X(p.t[0]), H - padB);
    g.closePath();
    g.fillStyle = grad;
    g.fill();
    g.restore();
    g.strokeStyle = colors[si]; g.lineWidth = 1.5; g.setLineDash([]); g.globalAlpha = 0.9;
    trace((x, y) => g.lineTo(x, y));
